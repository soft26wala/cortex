/**
 * Retrieves property listings from localStorage if available, or returns initial properties catalog.
 */
export function getStoredProperties(): PropertyItem[] {
  if (typeof window === 'undefined') return INITIAL_PROPERTIES
  try {
    const data = localStorage.getItem('proptis_properties_data')
    if (data) {
      const parsed = JSON.parse(data)
      if (Array.isArray(parsed) && parsed.length > 0) return parsed
    }
  } catch (e) {
    console.error('Error loading stored properties from localStorage:', e)
  }
  return INITIAL_PROPERTIES
}

/**
 * Persists property listings to localStorage.
 */
export function saveStoredProperties(properties: PropertyItem[]) {
  if (typeof window === 'undefined') return
  try {
    localStorage.setItem('proptis_properties_data', JSON.stringify(properties))
  } catch (e) {
    console.error('Error saving properties to localStorage:', e)
  }
}
